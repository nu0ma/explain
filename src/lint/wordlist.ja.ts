// 日本語の STE 検査で使う語の一覧。

// 冗長な動詞句 → 言い換え。noun があれば直前の名詞を使った例を示す（例：確認を行う → 確認する）。
// 長いものから照合し、照合済みの範囲は短いもので二重に数えない。
export const JA_VERBOSE = Object.freeze([
  { re: /実施を行(?:う|い|っ|わ)/g, label: '実施を行う', fix: () => '実施する' },
  { re: /することができ(?:る|ます|ない|ません)?/g, label: 'することができる', fix: (noun) => `${noun}できる` },
  { re: /させていただ(?:く|き|け|い)/g, label: 'させていただく', fix: (noun) => (noun ? `${noun}する` : 'する') },
  { re: /を行います/g, label: 'を行います', fix: (noun) => (noun ? `${noun}します` : '〜します') },
  { re: /を行(?:う|っ|わ|い|え)/g, label: 'を行う', fix: (noun) => (noun ? `${noun}する` : '〜する') },
  { re: /を実施(?:する|します|した|して|し)/g, label: 'を実施する', fix: (noun) => (noun ? `${noun}する` : '〜する') },
  { re: /ということ/g, label: 'ということ', fix: () => 'こと（または削る）' },
]);

