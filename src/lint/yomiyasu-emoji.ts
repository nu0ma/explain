const hex = (cp: number) => `\\u{${cp.toString(16)}}`;

function characterClass(ranges: readonly Range[]): string {
  return `[${ranges.map(([lo, hi]) => (lo === hi ? hex(lo) : `${hex(lo)}-${hex(hi)}`)).join('')}]`;
}

function flagPattern(): string {
  const seconds = new Map<string, string[]>();
  for (const code of [...FLAG_REGION_CODES].sort()) seconds.set(code[0], [...(seconds.get(code[0]) ?? []), code[1]]);
  const regional = (ch: string) => 0x1f1e6 + ch.charCodeAt(0) - 'A'.charCodeAt(0);
  const groups = [...seconds].map(([first, rest]) => {
    const firstCp = regional(first);
    return characterClass([[firstCp, firstCp]]) + characterClass(rest.map((ch): Range => [regional(ch), regional(ch)]));
  });
  return `(?:${groups.join('|')})`;
}

const EMOJI = new RegExp(
  '(?![\\u2713\\u2714\\u2717\\u2718\\u26A0](?!\\uFE0F))(?:'
  + flagPattern()
  + '|[0-9#*]\\uFE0F\\u20E3'
  + `|${characterClass(EXPLICIT_VARIATION_BASES)}\\uFE0F`
  + `|${characterClass(REGISTERED_TEXT_BASES)}(?!\\uFE0E)`
  + `|${characterClass(OTHER_BASES)})`,
  'gu',
);

export function emojiMatches(text: string): string[] {
  return text.match(EMOJI) ?? [];
}
